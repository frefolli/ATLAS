"""«Importa ADR…» of the model tree: the sheets of the architectural decisions (X-1) in Excel, one ADR per file (the
sheets of the teams) or one per worksheet (the file generated by ATLAS), in any template of the types. Shown, ADR by
ADR, as they become in the model before they are created (see storage.adr_sheets): the fields imported and what is
not imported as written, and why. An ADR whose ID is already in the model is not imported again."""
from pathlib import Path

from PySide6.QtCore import Qt
from PySide6.QtGui import QBrush, QColor
from PySide6.QtWidgets import (QDialog, QDialogButtonBox, QFileDialog, QHeaderView, QLabel, QMessageBox, QPushButton,
                               QTreeWidget, QTreeWidgetItem, QVBoxLayout)

from arcadia_tool.model.schema import KINDS_BY_NAME
from arcadia_tool.storage.adr_sheets import DUPLICATE, INVALID, PRESENT, create_adrs, plan_adrs, read_adr_sheets
from arcadia_tool.ui.theme import MUTED, icon

ADR_KIND = KINDS_BY_NAME["adr"]

GREEN, AMBER, RED = "#166534", "#92400E", "#B42318"
COLUMNS = ("Applica", "ADR / campo", "Tipo di decisione", "Proponente", "Cosa succede nel modello")
TICK, NAME, TYPE, PROPOSER, OUTCOME = range(len(COLUMNS))


def describe(p):
    """(what the import does with the ADR, its colour)."""
    if p.outcome == INVALID:
        return "Tipo di decisione non riconosciuto: non si importa", RED
    if p.outcome == PRESENT:
        return f"{p.written_id} è già nel modello («{p.existing.get('title') or ''}»): non si importa", MUTED
    if p.outcome == DUPLICATE:
        return f"{p.written_id} è già in un altro file scelto: non si importa", RED
    who = p.ident or "un ID dato da ATLAS"
    if p.warnings:
        n = len(p.warnings)
        return f"Nuova ADR {who}, {n} {'avviso' if n == 1 else 'avvisi'}: vedi sotto", AMBER
    return f"Nuova ADR {who}", GREEN


class ImportAdrsDialog(QDialog):
    """The ADR of the files chosen, each with a tick («Applica», on at first for those to import) and its fields."""

    def __init__(self, project, paths, parent=None):
        super().__init__(parent)
        self.project, self.paths = project, [Path(p) for p in paths]
        self.created, self.imported = [], {}  # the ADR created; {id(planned ADR) → ADR created} (the report)
        self.setWindowTitle("Importa ADR da Excel")
        sheets, self.failed = read_adr_sheets(self.paths)
        self.planned = plan_adrs(project.model, sheets)
        layout = QVBoxLayout(self)
        files = self.paths[0].name if len(self.paths) == 1 else f"{len(self.paths)} file"
        layout.addWidget(QLabel(f"Anteprima dell'import · decisioni architetturali (ADR) da {files}",
                                objectName="cardTitle"))
        layout.addWidget(QLabel(
            "Il modello non cambia finché non premi «Importa». Il tipo di ogni ADR si riconosce dalla scheda (anche "
            "nel template delle prime versioni) e ogni riga è abbinata al campo del tipo con la stessa etichetta; i "
            "testi guida del template («es. …», «Calcolato da ATLAS…») non si importano. L'ID è quello del nome del "
            "file o del titolo, se nel modello è libero; lo stato è «Proposta»: la Design Authority decide in ATLAS. "
            "Ciò che non si può impostare così com'è scritto (più domini di destinazione, un team o un dominio non "
            "trovato) resta nelle note della motivazione ed è indicato sotto l'ADR. Togli la spunta a ciò che non "
            "vuoi importare.", objectName="muted", wordWrap=True))
        self.counts = QLabel(objectName="formLabel", wordWrap=True)
        layout.addWidget(self.counts)
        self.tree = QTreeWidget()
        self.tree.setHeaderLabels(COLUMNS)
        self.tree.setAlternatingRowColors(True)
        header = self.tree.header()
        header.setSectionResizeMode(QHeaderView.Interactive)
        header.setSectionResizeMode(TICK, QHeaderView.ResizeToContents)
        header.setSectionResizeMode(NAME, QHeaderView.Stretch)
        header.setStretchLastSection(False)
        for column, width in ((TYPE, 230), (PROPOSER, 200), (OUTCOME, 360)):
            header.resizeSection(column, width)
        self._fill()
        self.tree.itemChanged.connect(self._count)
        layout.addWidget(self.tree, 1)
        buttons = QDialogButtonBox(QDialogButtonBox.Cancel)
        buttons.button(QDialogButtonBox.Cancel).setText("Annulla")
        self.import_button = QPushButton(icon("mdi6.import", "white"), "Importa")
        self.import_button.setProperty("primary", True)
        buttons.addButton(self.import_button, QDialogButtonBox.AcceptRole)
        self.import_button.clicked.connect(self.import_adrs)
        buttons.rejected.connect(self.reject)
        layout.addWidget(buttons)
        self.resize(1300, 760)
        self._count()

    def _child(self, row, name, outcome, color):
        child = QTreeWidgetItem(["", name, "", "", outcome])
        child.setForeground(OUTCOME, QBrush(QColor(color)))
        child.setToolTip(NAME, name[:800])
        child.setToolTip(OUTCOME, outcome[:800])
        child.setFlags(child.flags() & ~Qt.ItemIsUserCheckable)
        row.addChild(child)
        return child

    def _fill(self):
        model = self.project.model
        self.entries = []  # (planned ADR, its row)
        for p in self.planned:
            text, color = describe(p)
            team = model.get(p.values.get("proposer")) if p.values.get("proposer") else None
            proposer = " · ".join(t for t in ((team.get("id") if team else ""), p.values.get("proposer_member"))
                                  if t)
            name = " · ".join(t for t in (p.ident or p.written_id, p.title) if t) or p.sheet.path.name
            row = QTreeWidgetItem(["", name, p.adr_type or "—", proposer or "—", text])
            where = p.sheet.path.name + (f" · foglio {p.sheet.sheet}" if not p.sheet.single else "")
            row.setToolTip(NAME, f"{name}\n{where}")
            row.setToolTip(OUTCOME, text)
            row.setForeground(OUTCOME, QBrush(QColor(color)))
            if p.applicable:
                row.setFlags(row.flags() | Qt.ItemIsUserCheckable)
                row.setCheckState(TICK, Qt.Checked)
            else:
                row.setFlags(row.flags() & ~Qt.ItemIsUserCheckable)
            self.tree.addTopLevelItem(row)
            if p.applicable or p.outcome == INVALID:
                for label, value in p.shown:
                    self._child(row, f"{label}: {value}", "Si importa", GREEN)
                kept = ADR_KIND.field(p.note_field).label if p.note_field else ""
                for warning in p.warnings:
                    self._child(row, warning, f"Riportato nelle note di «{kept}»" if kept and warning in p.noted
                                else "Da verificare", AMBER)
            self.entries.append((p, row))
        for path, why in self.failed:
            row = QTreeWidgetItem(["", path.name, "", "", f"Non si legge: {why}"])
            row.setForeground(OUTCOME, QBrush(QColor(RED)))
            row.setFlags(row.flags() & ~Qt.ItemIsUserCheckable)
            self.tree.addTopLevelItem(row)

    def chosen(self):
        return [p for p, row in self.entries if p.applicable and row.checkState(TICK) == Qt.Checked]

    def _count(self, *_args):
        chosen = self.chosen()
        present = sum(1 for p in self.planned if p.outcome == PRESENT)
        warned = sum(1 for p in chosen if p.warnings)
        text = (f"{len(self.planned)} ADR nei file · si importano {len(chosen)}"
                f"{f', di cui {warned} con avvisi' if warned else ''} · già nel modello: {present}")
        invalid = sum(1 for p in self.planned if p.outcome in (INVALID, DUPLICATE))
        if invalid:
            text += f" · non importabili: {invalid}"
        if self.failed:
            text += f" · file non letti: {len(self.failed)}"
        self.counts.setText(text)
        self.import_button.setEnabled(bool(chosen))

    def import_adrs(self):
        chosen = self.chosen()
        # An ADR that another one says supersedes it: set only if that one is imported too.
        imported = {p.ident for p in chosen if p.ident}
        for p in chosen:
            if p.values.get("_superseded_by") not in imported:
                p.values.pop("_superseded_by", None)
        self.created = create_adrs(self.project, chosen)
        self.imported = {id(p): adr for p, adr in zip(chosen, self.created)}
        self.accept()


def save_report(dialog, parent=None, author="", path=None):
    """At the end of the import: asked whether to save its report (path: given, without asking). Returns the path
    written, or None."""
    from datetime import date

    from arcadia_tool.storage.adr_import_report import write_adr_import_report

    project = dialog.project
    if path is None:
        count = len(dialog.created)
        if QMessageBox.question(
                parent, "Importa ADR", f"Import completato: {count} {'ADR creata' if count == 1 else 'ADR create'}."
                "\n\nSalvare un report dell'importazione? Riporta in Excel le ADR importate e quelle non importate "
                "(con il motivo), i campi importati, le scelte fatte (ID, tipo, proponente…) e gli avvisi.",
                QMessageBox.Yes | QMessageBox.No, QMessageBox.Yes) != QMessageBox.Yes:
            return None
        suggested = str(project.path.parent / f"Report_import_ADR_{date.today():%Y-%m-%d}.xlsx")
        path, _ = QFileDialog.getSaveFileName(parent, "Salva il report dell'importazione", suggested,
                                              "Excel (*.xlsx)")
        if not path:
            return None
    try:
        return write_adr_import_report(project.model, dialog.planned, dialog.imported, dialog.failed, path,
                                       project.name, author)
    except Exception as exc:  # e.g. the file open in Excel
        QMessageBox.warning(parent, "Importa ADR", f"Il report non si può salvare: {exc}")
        return None


def import_adrs(project, parent=None, paths=None, author=""):
    """The files chosen by the user (paths: given, without asking), then what is imported; at the end, the report
    of the import if the user wants it. Returns the ADR created; empty if cancelled."""
    if paths is None:
        paths, _ = QFileDialog.getOpenFileNames(parent, "Importa ADR da Excel (uno o più file)",
                                                str(project.path.parent), "Excel (*.xlsx *.xlsm)")
        if not paths:
            return []
    try:
        dialog = ImportAdrsDialog(project, paths, parent)
    except Exception as exc:  # e.g. a file locked by Excel while it is read
        QMessageBox.warning(parent, "Importa ADR", f"I file non si possono leggere: {exc}")
        return []
    if not dialog.planned:
        reasons = "\n".join(f"• {p.name}: {why}" for p, why in dialog.failed)
        QMessageBox.information(parent, "Importa ADR", "Nessuna scheda ADR nei file scelti." +
                                (f"\n\n{reasons}" if reasons else ""))
        return []
    if not dialog.exec():
        return []
    save_report(dialog, parent, author)
    return dialog.created
