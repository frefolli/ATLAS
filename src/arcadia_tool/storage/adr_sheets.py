"""The sheets of the architectural decisions (X-1) kept in Excel, one ADR per workbook, in any of the templates of
the types (generated by ATLAS, «Template_X-1.nn_ADR_…») or in the template of the first versions (one type,
«Riallocazione di sezione», labels slightly different): read to import them into the model (see ui.import_adrs).

The type is recognized from «Tipo di decisione» (or the heading «Dettagli: …» of the sheet, or its title), then each
row is matched by its label to a field of that type: the texts of guide of the templates («es. DF07 · Odometria»,
«Calcolato da ATLAS…») are ignored, the references (SRS items, domains, teams, functions…) resolved in the model.
What cannot be set (a destination of several domains, a team or a domain not found, a row of no field) is kept in
the notes of the ADR and reported as a warning."""
import re
from dataclasses import dataclass, field
from datetime import date, datetime
from pathlib import Path

import openpyxl

from arcadia_tool.documents.adr import hint
from arcadia_tool.model.adr import PROPOSED, common_fields, same_section, section_of, type_fields
from arcadia_tool.model.schema import (ADR_SECTION, ADR_TYPE_LABELS, BOOL, DA_DECISION, ENUM, KINDS_BY_NAME,
                                       MULTIENUM, REF, REFS, TABLE, TEXT)
from arcadia_tool.model.teams import member_rows, person_key

ADR = KINDS_BY_NAME["adr"]
ADR_ID = re.compile(r"\bADR[\s_-]*0*(\d+)\b", re.IGNORECASE)
DOMAIN_ID = re.compile(r"\bDF\s*[-_]?\s*0*(\d+)\b", re.IGNORECASE)
# A clause (3.14.1.3), its list items («3.15.9.5 a) b)»), a subset of a section («3.9.2.x»).
CLAUSE = re.compile(r"(?<![\d.])(\d+(?:\.\d+)+)((?:\s*\b[a-z]\))*)(\.x\b)?", re.IGNORECASE)
# Rows of the header of the document (three label and value pairs per row: A–B, C–D, E–F).
HEADER = {"template": "template", "team": "team", "team / dominio": "team", "versione": "version",
          "autore": "author", "revisore": "reviewer", "data": "date", "stato": "sheet_status",
          "baseline srs": "baseline", "rif. capella / doors": "reference"}
# Rows that are not fields: the identification of the ADR, the headings of the sections, the intro of the template.
STRUCTURE = ("identificazione", "descrizione", "decisione della da", "dettagli:", "x-1 ", "x-1·", "template arcadia",
             "scopo.", "come si compila", "legenda", "chi compila")
# Texts of the template to replace: what is left of them is no value.
PLACEHOLDERS = ("es. ", "uno o più", "uno o piu", "una o più", "calcolato da atlas", "gg/mm/aaaa",
                "scritto da atlas", "uno dei membri del team")
EMPTY = {"", "/", "-", "—", "–", "n/a", "na", "nessuno", "nessuna"}
# Words around the references, said for clarity («Clausole:», «Sezione 6.3», «DF11 & DF12»): no information.
FILLER = {"clausola", "clausole", "sezione", "sezioni", "e", "o", "ed", "od", "oppure", "and", "or", "&", "di",
          "della", "delle", "del", "dei", "il", "la", "le", "i"}
# The template of the first versions: its labels, then renamed (see the fields of ADR_SECTION).
OLD_LABELS = {"sezione o clausola da riallocare": "realloc_item"}


@dataclass
class AdrSheet:
    path: Path
    sheet: str
    header: dict  # {template, team, author, date, sheet_status…}: the data of the document
    rows: list  # [(row, label, value)]: the fields, as written (lines kept)
    tables: dict  # {label: [{heading: text}]}: the tables (options, candidate producers…)
    title: str = ""  # the first row: «X-1 · Decisione architetturale (ADR) · <type>»
    headings: list = field(default_factory=list)  # the headings of the sections («Dettagli: <type>»…)
    single: bool = True  # the only ADR of its workbook: its file may be named after it (ADR-005.xlsx)


def _text(value):
    if value is None:
        return ""
    if isinstance(value, (datetime, date)):
        return f"{value:%d/%m/%Y}"
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    lines = [" ".join(line.split()) for line in str(value).replace("\r", "").split("\n")]
    return "\n".join(line for line in lines if line)


def _key(label, brackets=True):
    """A label compared without case, spaces or the last vowel of its words («Sezione o clausola da riallocare» is
    «Sezioni o clausole da riallocare»); brackets False: without what is in parentheses too («Dominio principale
    proposto (destinazione)» is «Dominio principale proposto»)."""
    text = (label or "").casefold().replace("/", " ")
    if not brackets:
        text = re.sub(r"\([^)]*\)", " ", text)
    words = re.findall(r"[\w']+", text)
    return " ".join(w[:-1] if len(w) > 3 and w[-1] in "aeiou" else w for w in words)


def _label(text):
    return " ".join((text or "").split())


def _is_structure(label):
    lower = label.casefold()
    return any(lower.startswith(s) for s in STRUCTURE)


def read_adr_workbook(path):
    """The ADR of a workbook: one per worksheet with «ID e titolo» (a sheet of the teams, or the file of the ADR
    generated by ATLAS, a sheet per ADR after the register)."""
    workbook = openpyxl.load_workbook(path, read_only=True, data_only=True)
    try:
        sheets = [(ws.title, [[_text(v) for v in row] for row in ws.iter_rows(values_only=True)])
                  for ws in workbook.worksheets]
    finally:
        workbook.close()
    found = [(n, c) for n, c in sheets if any(r and r[0].casefold() == "id e titolo" for r in c)]
    return [_read(Path(path), name, cells, len(found) == 1) for name, cells in found]


def _read(path, name, cells, single):
    header, rows, tables, title, headings = {}, [], {}, "", []
    table = None  # (label, {column: heading}) of the table being read
    for r, row in enumerate(cells, start=1):
        row = row + [""] * (6 - len(row))
        label = row[0]
        if r == 1 or (not title and label.casefold().startswith("x-1")):
            title = title or label
            continue
        labels = [row[c].casefold() for c in (0, 2, 4)]
        if labels[0] in HEADER and labels[1] in HEADER:  # a row of the header of the document
            for c in (0, 2, 4):
                if row[c].casefold() in HEADER:
                    header[HEADER[row[c].casefold()]] = row[c + 1]
            continue
        values = [v for v in row[1:] if v]
        if table is not None:
            if table[1] is None:  # the row of the headings
                table = (table[0], {c: h for c, h in enumerate(row) if h})
                continue
            if not any(row) or (label and (_is_structure(label) or _key(label) in FIELD_LABELS | TABLE_LABELS)):
                table = None  # the end of the table: an empty row, a heading, the next field
            else:
                tables[table[0]].append({h: row[c] for c, h in table[1].items() if row[c]})
                continue
        if not label:
            continue
        if _is_structure(label):
            headings.append(label)
            continue
        if not values and _key(label) in TABLE_LABELS:
            table = (label, None)
            tables[label] = []
            continue
        rows.append((r, label, "\n".join(values)))
    return AdrSheet(path, name, header, rows, tables, title, headings, single)


TABLE_LABELS = {_key(f.label) for f in ADR.fields if f.type == TABLE}
FIELD_LABELS = {_key(f.label) for f in ADR.fields if f.type != TABLE} | {_key("ID e titolo"),
                                                                        _key("Tipo di decisione")}


