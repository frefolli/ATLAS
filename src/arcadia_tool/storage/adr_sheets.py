NEW, PRESENT, DUPLICATE, INVALID = "new", "present", "duplicate", "invalid"


@dataclass
class PlannedAdr:
    sheet: AdrSheet
    ident: str = ""  # the ID the ADR gets ("" : given by ATLAS)
    written_id: str = ""  # the ID as written (file name, title)
    title: str = ""
    adr_type: str = None
    values: dict = field(default_factory=dict)  # the fields of the ADR
    shown: list = field(default_factory=list)  # [(label, text)]: what is imported, as shown in the summary
    warnings: list = field(default_factory=list)  # what is not imported as written, and why
    notes: list = field(default_factory=list)  # kept in the text of the ADR (its motivation)
    noted: list = field(default_factory=list)  # the warnings whose text is among the notes
    note_field: str = None  # the field the notes are kept in (None: the type has no free text, they are not kept)
    choices: list = field(default_factory=list)  # how the import decided what is not written plainly (the report)
    outcome: str = NEW
    existing: object = None  # the ADR of the model with the same ID

    @property
    def applicable(self):
        return self.outcome == NEW


def _placeholder(text, f=None):
    lower = text.casefold().strip()
    if lower in EMPTY:
        return True
    if any(lower.startswith(p) for p in PLACEHOLDERS):
        return True
    if f is not None:
        guide = hint(f)
        if guide and " ".join(guide.split()).casefold() == " ".join(lower.split()):
            return True
        if f.type == ENUM and " / ".join(f.options).casefold() == lower:
            return True
    return lower in ("adr-nnn", "bozza / in revisione / approvato")


def _leftover(text, removed):
    """What a text says besides the references found in it (their IDs and names, the connecting words)."""
    rest = text.casefold()
    for r in sorted((r for r in removed if r), key=len, reverse=True):
        rest = rest.replace(r.casefold(), " ")
    words = [w for w in re.findall(r"[\w']+", rest) if w not in FILLER and not w.isdigit()]
    return " ".join(words)


def _domain_leftover(text):
    """What a list of domains says besides them: «DF07 - Train Movement…» says nothing more (the name after the ID
    is the domain), «DF10 · Radio… (3.9.1.1 c: radio infill unit)» its parentheses, «Da definire» all of it."""
    rest = []
    # Italian conjunctions only: «and» is in the names of the domains («Mode and Level Management»).
    for part in re.split(r"[,;\n&]|\s+(?:o|e|oppure)\s+", text):
        inside = " ".join(re.findall(r"\(([^)]*)\)", part))
        bare = re.sub(r"\([^)]*\)", " ", part)
        if DOMAIN_ID.search(bare):
            bare = ""
        rest.append(f"{bare} {inside}")
    return _leftover(" ".join(rest), [])


def _letters(text):
    return re.sub(r"[^a-z0-9]", "", text.casefold())


def _abbreviates(token, words):
    """«Unimib» is «Università degli Studi di Milano Bicocca», «FBK» «Fondazione Bruno Kessler»: the token is made of
    the starts of some of the words, in their order, the first word included."""
    token, words = _letters(token), [_letters(w) for w in words if _letters(w)]

    def match(t, i, first):
        if not t:
            return True
        for j in range(i, len(words)):
            if first and j != i:
                return False
            w = words[j]
            for n in range(min(len(w), len(t)), 0, -1):
                if w[:n] == t[:n] and match(t[n:], j + 1, False):
                    return True
        return False

    return len(token) >= 2 and bool(words) and match(token, 0, True)


class Resolver:
    """The elements of the model referenced by the texts of a sheet."""

    def __init__(self, model):
        from arcadia_tool.ui.srs_reader import document_order

        self.model = model
        self.items = {e.get("id"): e for e in document_order(model) if e.get("id")}
        self.domains = {}
        for d in model.of_kind("domain"):
            m = DOMAIN_ID.search(d.get("id") or "")
            if m:
                self.domains[int(m[1])] = d
        self.teams = model.of_kind("team")

    # SRS items ---------------------------------------------------------------------------------------------------

    def requirements(self, text):
        """(items, what is written for each, problems)."""
        found, written, problems = [], [], []
        for m in CLAUSE.finditer(text):
            clause, subs, subset = m[1], m[2] or "", m[3]
            if self._sub_items(clause, subs, found, written):
                continue
            item = self.items.get(clause)
            if item is None:
                problems.append(f"«{m[0].strip()}» non trovata tra le voci SRS del progetto")
                continue
            if subs.strip():
                problems.append(f"«{m[0].strip()}»: sottovoci non trovate, si riferisce alla clausola {clause}")
            if subset:
                problems.append(f"«{m[0].strip()}»: un sottoinsieme non precisato, si riferisce alla sezione {clause}")
            self._add(item, m[0].strip(), found, written)
        return found, written, problems

    def _sub_items(self, clause, subs, found, written):
        """«3.15.9.5 a)» or «3.5.3.4 b) f)»: the list items, when they are SRS items of the project."""
        letters = re.findall(r"[a-z]\)", subs, re.IGNORECASE)
        if not letters:
            return False
        whole = self.items.get(f"{clause} {' '.join(letters)}")  # a nested item («3.6.2.2.2 a) a)»)
        items = [whole] if whole is not None else [self.items.get(f"{clause} {s}") for s in letters]
        if not items or any(i is None for i in items):
            return False
        for item in items:
            self._add(item, item.get("id"), found, written)
        return True

    @staticmethod
    def _add(item, text, found, written):
        if item.uuid not in {i.uuid for i in found}:
            found.append(item)
            written.append(text)

    # other elements ----------------------------------------------------------------------------------------------

    def domains_in(self, text):
        """(domains, the texts naming them)."""
        found, names = [], []
        for m in DOMAIN_ID.finditer(text):
            d = self.domains.get(int(m[1]))
            if d is not None and d not in found:
                found.append(d)
                names += [m[0], d.get("name") or ""]
        lower = text.casefold()
        for d in self.domains.values():  # by name alone
            name = (d.get("name") or "").casefold()
            if d not in found and len(name) > 3 and name in lower:
                found.append(d)
                names.append(name)
        return found, names

    def team(self, text):
        """The team named by a text (its ID, name or abbreviation), or the team of the domain it names; None."""
        if not text:
            return None
        key = " ".join(text.casefold().split())
        token = re.split(r"\s*[·•|-]\s*|\s+", key)[0].strip()
        for t in self.teams:  # «T3», «INTECS», «T3 · INTECS», «T3 INTECS» (as ATLAS writes it)
            ident, name = (t.get("id") or "").casefold(), " ".join((t.get("name") or "").casefold().split())
            if key in (ident, name) or (ident and token == ident) or (name and key.endswith(name)):
                return t
        matches = [t for t in self.teams if _abbreviates(token, (t.get("name") or "").split())]
        if len(matches) == 1:
            return matches[0]
        domains, _names = self.domains_in(text)
        if len(domains) == 1 and domains[0].get("team"):
            return self.model.get(domains[0].get("team"))
        return None

    def member(self, team, text):
        """The member of the team written as «Guido Ioele», «Ioele Guido» or «G. Ioele»; "" if none."""
        if team is None or not text:
            return ""
        key = person_key(text)
        rows = member_rows(team)
        exact = next((r.get("name") for r in rows if person_key(r.get("name")) == key), "")
        if exact:
            return exact
        initial = re.match(r"^\s*([^\W\d])\.\s*(.+)$", text)
        if initial:
            first, surname = initial[1].casefold(), person_key(initial[2])
            for r in rows:
                words = (r.get("name") or "").split()
                if len(words) >= 2 and person_key(" ".join(words[1:])) == surname and \
                        words[0][:1].casefold() == first:
                    return r.get("name")
        return ""

    def element(self, kinds, text):
        """An element of the kinds by its ID or name, or None."""
        key = " ".join(text.split()).casefold()
        for kind in kinds:
            for e in self.model.of_kind(kind):
                if key in ((e.get("id") or "").casefold(), " ".join((e.get("name") or "").split()).casefold()):
                    return e
        token = re.split(r"\s+[·•–—-]\s+|\s+", key)[0]  # «SF-DF07-03 · Stimare la velocità»
        for kind in kinds:
            for e in self.model.of_kind(kind):
                if token and token == (e.get("id") or "").casefold():
                    return e
        return None


def _adr_number(text):
    m = ADR_ID.search(text or "")
    return int(m[1]) if m else None


def _adr_type(sheet):
    """(type, note): from «Tipo di decisione», else the heading of the details, else the title of the sheet."""
    written = next((v for _r, label, v in sheet.rows if label.casefold() == "tipo di decisione"), "")
    lower = written.casefold().strip()
    exact = next((t for t in ADR_TYPE_LABELS if t.casefold() == lower), None)
    if exact:
        return exact, ""
    starts = next((t for t in ADR_TYPE_LABELS if lower.startswith(t.casefold())), None)
    if starts:
        return starts, f"Tipo di decisione indicato nel file: «{written}»"
    # The template of the sheet: its heading «Dettagli: <type>», or its title «X-1 · … · <type>».
    heading = next((h for h in sheet.headings if h.casefold().startswith("dettagli:")), "")
    for text in (heading, sheet.title.split("·")[-1] if sheet.title else ""):
        text = text.casefold().replace("dettagli:", "").strip()
        found = next((t for t in ADR_TYPE_LABELS if text and t.casefold().startswith(text)), None)
        if found:
            return found, (f"Tipo di decisione «{written}» non previsto: importata come «{found}», il modello della "
                           "scheda") if written else ""
    return None, f"Tipo di decisione «{written}» non riconosciuto" if written else "Tipo di decisione mancante"


def note_field(adr_type):
    """The text of the ADR where what is not imported as written is kept: the motivation of its type."""
    details = [f for f in type_fields(adr_type) if f.type == TEXT and f.stored and not f.computed]
    reason = next((f for f in details if "reason" in f.name), None)
    if reason is not None or details:
        return (reason or details[0]).name
    common = [f.name for f in common_fields(adr_type) if f.type == TEXT and f.section != DA_DECISION]
    return next((n for n in ("rationale", "context", "decision") if n in common), common[0] if common else None)


class _Plan:
    """The fields of one sheet: what goes into the ADR, what is shown, what is warned."""

    def __init__(self, resolver, planned):
        self.r, self.p = resolver, planned

    def show(self, label, text):
        self.p.shown.append((label, text))

    def warn(self, text, note=None):
        self.p.warnings.append(text)
        if note:
            self.p.notes.append(note)
            self.p.noted.append(text)

    def value(self, f, label, text):
        """The value of a field written as text, or None."""
        r, p = self.r, self.p
        if f.type in (TEXT,) or (f.type not in (REF, REFS, ENUM, MULTIENUM, BOOL, TABLE)):
            return text
        if f.type == ENUM:
            option = next((o for o in f.options if o.casefold() == text.casefold().strip()), None) or \
                next((o for o in f.options if text.casefold().startswith(o.casefold())), None)
            if option is None:
                self.warn(f"{label}: «{text}» non è tra le scelte del campo", f"{label}: {text}")
            return option
        if f.type == MULTIENUM:
            chosen = [o for o in f.options if re.search(rf"(?<!\w){re.escape(o)}(?!\w)", text, re.IGNORECASE)]
            return chosen or None
        if f.type == BOOL:
            return text.casefold().strip() in ("sì", "si", "yes", "x", "true", "vero")
        kinds = f.ref_kinds
        if kinds == ("requirement",):
            items, written, problems = r.requirements(text)
            for problem in problems:
                self.warn(f"{label}: {problem}")
            words = _leftover(text, [w for w in written] + [m[0] for m in CLAUSE.finditer(text)])
            if words:  # «Parte della clausola…», «e relative sottoclausole»: said in the notes
                p.notes.append(f"{label}: {text}")
                if not problems:
                    self.warn(f"{label}: il testo «{text}» è riportato nelle note")
            if not items:
                return None
            if f.type == REF:
                if len(items) > 1:
                    self.warn(f"{label}: più voci, si importa la prima ({items[0].get('id')})", f"{label}: {text}")
                return items[0].uuid
            return [i.uuid for i in items]
        if kinds == ("domain",):
            domains, names = r.domains_in(text)
            words = _domain_leftover(text)
            if f.type == REF and len(domains) > 1:
                self.warn(f"{label}: più domini indicati («{text}»), da scegliere: il campo resta vuoto",
                          f"{label}: {text}")
                return None
            if not domains:
                self.warn(f"{label}: «{text}» non è un dominio del progetto: il campo resta vuoto", f"{label}: {text}")
                return None
            if words:
                p.notes.append(f"{label}: {text}")
            return domains[0].uuid if f.type == REF else [d.uuid for d in domains]
        if kinds == ("team",):
            team = r.team(text)
            if team is None:
                self.warn(f"{label}: «{text}» non è un team del progetto", f"{label}: {text}")
                return None
            return team.uuid
        parts = [t.strip() for t in re.split(r"[;\n]|,(?![^(]*\))", text) if t.strip()] if f.type == REFS else [text]
        found = []
        for part in parts:
            e = r.element(kinds, part)
            if e is None:
                self.warn(f"{label}: «{part}» non trovato nel modello", f"{label}: {part}")
            elif e.uuid not in found:
                found.append(e.uuid)
        if not found:
            return None
        return found[0] if f.type == REF else found

    def table(self, f, rows):
        """The rows of a table field: each column by its heading."""
        columns = {_key(c.label): c for c in f.columns}
        result = []
        for row in rows:
            values = {}
            for heading, text in row.items():
                c = columns.get(_key(heading))
                if c is None or _placeholder(text):
                    continue
                if c.choices == "split_domain_items":  # an SRS item of the domain split
                    items, _w, _p = self.r.requirements(text)
                    if not items:
                        self.warn(f"{f.label}: «{text}» non è una voce SRS del progetto", f"{f.label}: {text}")
                        continue
                    values[c.name] = items[0].uuid
                elif c.choices == "shared_derived":  # a derived requirement (SA-4) of the clauses shared
                    e = self.r.element(("derived_requirement",), text)
                    if e is None:
                        self.warn(f"{f.label}: «{text}» non è un requisito derivato del progetto",
                                  f"{f.label}: {text}")
                        continue
                    values[c.name] = e.uuid
                elif c.type == REF:
                    e = self.r.element(c.ref_kinds, text) if c.ref_kinds != ("team",) else self.r.team(text)
                    if e is None:
                        self.warn(f"{f.label}: «{text}» non trovato nel modello", f"{f.label} · {c.label}: {text}")
                        continue
                    values[c.name] = e.uuid
                elif c.type == ENUM:
                    option = next((o for o in c.options if o.casefold() == text.casefold()), None)
                    if option:
                        values[c.name] = option
                else:
                    values[c.name] = text
            if values:
                result.append(values)
        return result


def plan_adr(model, sheet, resolver=None, taken=()):
    """What the sheet becomes in the model. taken: the IDs of the ADR planned before (the other files)."""
    r = resolver or Resolver(model)
    p = PlannedAdr(sheet)
    plan = _Plan(r, p)
    p.adr_type, type_note = _adr_type(sheet)
    if type_note:
        plan.warn(type_note, type_note)
    if p.adr_type:
        p.choices.append(f"Tipo di decisione «{p.adr_type}»: " + ("dal modello della scheda" if type_note else
                                                                 "da «Tipo di decisione»"))
    if p.adr_type is None:
        p.outcome = INVALID
    # The ID: the one of the name of the file (ADR-0010.xlsx), else of «ID e titolo»; the title after it.
    written = next((v for _r, label, v in sheet.rows if label.casefold() == "id e titolo"), "")
    number_file = _adr_number(sheet.path.stem) if sheet.single else None
    number_title = _adr_number(written)
    number = number_file if number_file is not None else number_title
    p.written_id = f"ADR-{number:03d}" if number is not None else ""
    if number_file is not None and number_title is not None and number_file != number_title:
        plan.warn(f"Il titolo riporta ADR-{number_title:03d}, il nome del file {p.written_id}: si usa il nome del "
                  "file", f"ID e titolo nel file: {written}")
    title = ADR_ID.sub("", written, count=1) if number_title is not None else written
    p.title = re.sub(r"^[\s·•:–—\-]+", "", " ".join(title.split())).strip()
    existing = [a for a in model.of_kind("adr") if p.written_id and (a.get("id") or "").upper() == p.written_id]
    if p.outcome != INVALID and existing:
        p.outcome, p.existing = PRESENT, existing[0]
    elif p.outcome != INVALID and p.written_id in taken:
        p.outcome = DUPLICATE
    p.ident = p.written_id if p.outcome == NEW else ""
    if p.ident:
        p.choices.append(f"ID {p.ident}: " + (f"dal nome del file {sheet.path.name}" if number_file is not None
                                              else "da «ID e titolo»"))
    elif p.outcome == NEW:
        p.choices.append("ID: nessun numero nel file né nel titolo, lo genera ATLAS")
    if p.adr_type is None:
        return p
    values = {"adr_type": p.adr_type, "status": PROPOSED}
    if p.title:
        values["title"] = p.title
    fields = {f.name: f for f in [*type_fields(p.adr_type), *common_fields(p.adr_type)]}
    for name in ("superseded_by", "proposer", "proposer_member"):
        fields[name] = ADR.field(name)
    by_label = {_key(f.label): f for f in fields.values()}
    by_label.update({_key(k): fields[v] for k, v in OLD_LABELS.items() if v in fields})
    short = {}  # without the parentheses: only the labels that stay distinct («Proponente (team)» does not)
    for f in fields.values():
        short.setdefault(_key(f.label, False), []).append(f)
    loose = {k: fs[0] for k, fs in short.items() if len(fs) == 1}

    def field_of(label):
        return by_label.get(_key(label)) or loose.get(_key(label, False))

    status, written_team, written_member = "", "", ""
    for _r, label, text in sheet.rows:
        lower = label.casefold()
        if lower in ("id e titolo", "tipo di decisione"):
            continue
        if lower == "stato":
            status = text
            continue
        f = field_of(label)
        if f is None:
            if lower == "data della decisione":  # set by ATLAS when the DA decides
                continue
            if text and not _placeholder(text):
                plan.warn(f"«{_label(label)}» non è un campo del tipo «{p.adr_type}»: riportato nelle note",
                          f"{_label(label)}: {text}")
            continue
        if not text or _placeholder(text, f):
            continue
        if f.name == "proposer":
            written_team = text
            continue
        if f.name == "proposer_member":
            written_member = text
            continue
        if f.section == DA_DECISION:  # the decision of the DA: taken in ATLAS, by its members
            plan.warn(f"«{f.label}»: la decisione della DA si registra in ATLAS, non si importa", f"{f.label}: {text}")
            continue
        if f.computed or not f.stored:  # read from the model: compared with what is written
            _compare(plan, model, values, f, f.label, text)
            continue
        if f.by_tool:
            continue
        value = plan.value(f, f.label, text)
        if value in (None, "", []):
            continue
        if f.name == "superseded_by":
            continue  # resolved with the other files (see plan_adrs)
        values[f.name] = value
        plan.show(f.label, _shown(model, f, value))
    for label, rows in sheet.tables.items():
        f = field_of(label)
        if f is None or f.type != TABLE:
            continue
        rows = plan.table(f, rows)
        if rows:
            values[f.name] = rows
            plan.show(f.label, f"{len(rows)} righe")
    superseded = next((v for _r, label, v in sheet.rows if field_of(label) is ADR.field("superseded_by")
                       and v and not _placeholder(v, ADR.field("superseded_by"))), "")
    if superseded:
        p.values["_superseded_by"] = superseded
    # The proposer: the team written, else the one of the header; the member: written, else the author.
    team = r.team(written_team) if written_team else None
    team_from = f"da «Proponente (team)» («{written_team}»)" if team is not None else ""
    header_team = sheet.header.get("team", "")
    if team is None and header_team and not _placeholder(header_team):
        team = r.team(header_team)
        team_from = f"dall'intestazione della scheda (Team «{header_team}»)" if team is not None else ""
        if team is not None and written_team:
            plan.warn(f"Proponente (team): «{written_team}» non è un team, si usa quello dell'intestazione "
                      f"({team.get('id')} · {team.get('name')})", f"Proponente (team): {written_team}")
    if team is None and (written_team or header_team):
        what = written_team or header_team
        if not _placeholder(what):
            plan.warn(f"Proponente (team): «{what}» non è un team del progetto", f"Proponente (team): {what}")
    member_text = written_member or sheet.header.get("author", "")
    member = r.member(team, member_text) if team is not None else ""
    if team is None and member_text:  # the team of the member, when the team is not said
        for t in r.teams:
            member = r.member(t, member_text)
            if member:
                team = t
                team_from = f"il team del membro «{member_text}»"
                break
    if team is not None:
        values["proposer"] = team.uuid
        plan.show(ADR.field("proposer").label, f"{team.get('id')} · {team.get('name')}")
        p.choices.append(f"Proponente (team) {team.get('id')} · {team.get('name')}: {team_from}")
    else:
        p.choices.append("Proponente (team): non indicato o non riconosciuto, il campo resta vuoto")
    if member:
        values["proposer_member"] = member
        plan.show(ADR.field("proposer_member").label, member)
        source = "da «Proponente (membro del team)»" if written_member else "dall'autore della scheda"
        p.choices.append(f"Proponente (membro del team) {member}: {source} («{member_text}»)")
    else:
        if written_member and not _placeholder(written_member) and r.team(written_member) is None:
            plan.warn(f"Proponente (membro del team): «{written_member}» non è tra i membri del team",
                      f"Proponente (membro del team): {written_member}")
        # Not said, or not one of the members: the referent of the team, who answers for it.
        referent = r.member(team, team.get("referent") or "") if team is not None else ""
        if referent:
            values["proposer_member"] = referent
            plan.show(ADR.field("proposer_member").label, f"{referent} (referente del team: il file non indica "
                                                          "il membro)")
            p.choices.append(f"Proponente (membro del team) {referent}: il referente del team, perché il file non "
                             "indica un membro" + (f" («{member_text}»)" if member_text else ""))
        else:
            p.choices.append("Proponente (membro del team): non indicato e il team non ha un referente, il campo "
                             "resta vuoto")
    items = [model.get(u) for u in values.get("realloc_item") or []]
    if p.adr_type == ADR_SECTION and not same_section(model, items):  # the rule of the reallocation (A4)
        sections = sorted({(section_of(model, e) or e).get("id") for e in items})
        plan.warn(f"Le voci da riallocare sono di sezioni diverse ({', '.join(sections)}): un'ADR di riallocazione "
                  "riguarda una sola sezione, la Design Authority può chiederne la divisione")
    p.choices.append(f"Stato «{PROPOSED}»: sempre, la Design Authority decide in ATLAS" +
                     (f" (nel file «{status}»)" if status and not _placeholder(status, ADR.field("status")) else ""))
    if status and not _placeholder(status, ADR.field("status")) and status.casefold() != PROPOSED.casefold():
        plan.warn(f"Stato nel file «{status}»: si importa come «{PROPOSED}», la Design Authority decide in ATLAS",
                  f"Stato nel file: {status}")
    p.values.update(values)
    return p


def _compare(plan, model, values, f, label, text):
    """A field computed from the model (the domain of an SRS item now): what the file says, if different."""
    from arcadia_tool.model.adr import COMPUTED
    from arcadia_tool.model.element import Element

    if f.computed not in COMPUTED or f.ref_kinds != ("domain",):
        return
    probe = Element("adr", values=dict(values))
    computed = COMPUTED[f.computed](model, probe)
    now = [computed] if isinstance(computed, str) else list(computed or [])
    written, _names = plan.r.domains_in(text)
    if written and {d.uuid for d in written} != set(now):
        said = ", ".join(d.get("id") for d in written)
        model_ids = ", ".join(model.get(u).get("id") for u in now if model.get(u) is not None) or "nessuno"
        plan.warn(f"{label}: nel file {said}, nel modello {model_ids} (si usa il modello)")


def _shown(model, f, value):
    if f.type == REF:
        e = model.get(value)
        return (e.get("id") or model.label(e)) if e is not None else ""
    if f.type == REFS:
        return ", ".join((model.get(u).get("id") or model.label(model.get(u))) for u in value if model.get(u))
    if isinstance(value, list):
        return ", ".join(map(str, value))
    return str(value)


def plan_adrs(model, sheets):
    """What every sheet becomes, in the order of their IDs; the ADR they say supersede them resolved among the
    ADR of the model and those imported; the notes kept in the motivation of each."""
    resolver = Resolver(model)
    planned, taken = [], set()
    def number(s):
        n = _adr_number(s.path.stem) if s.single else None
        if n is None:
            n = _adr_number(next((v for _r, label, v in s.rows if label.casefold() == "id e titolo"), ""))
        return (n is None, n or 0, s.path.name, s.sheet)

    for sheet in sorted(sheets, key=number):
        p = plan_adr(model, sheet, resolver, taken)
        if p.ident:
            taken.add(p.ident)
        planned.append(p)
    ids = {(a.get("id") or "").upper(): a.uuid for a in model.of_kind("adr")}
    for p in planned:
        written = p.values.pop("_superseded_by", "")
        if not written:
            continue
        number = _adr_number(written)
        ident = f"ADR-{number:03d}" if number is not None else ""
        if ident in ids:
            p.values["superseded_by"] = ids[ident]
            p.shown.append((ADR.field("superseded_by").label, ident))
        elif ident in taken:
            p.values["_superseded_by"] = ident  # set when that ADR is created
            p.shown.append((ADR.field("superseded_by").label, f"{ident} (importata ora)"))
        else:
            warning = f"Superata da: «{written}» non è un'ADR del progetto"
            p.warnings.append(warning)
            p.notes.append(f"Superata da: {written}")
            p.noted.append(warning)
    for p in planned:
        if p.notes and p.adr_type:
            p.note_field = note_field(p.adr_type)
            if p.note_field:
                block = f"Note dell'import da {p.sheet.path.name}:\n" + "\n".join(f"- {n}" for n in p.notes)
                text = p.values.get(p.note_field) or ""
                p.values[p.note_field] = f"{text}\n\n{block}" if text else block
    return planned


def read_adr_sheets(paths):
    """The ADR of the files, and the files that could not be read or have none: ([AdrSheet], [(path, why)])."""
    sheets, failed = [], []
    for path in paths:
        try:
            found = read_adr_workbook(path)
        except Exception as exc:  # not a workbook, locked by Excel…
            failed.append((Path(path), str(exc) or exc.__class__.__name__))
            continue
        if found:
            sheets += found
        else:
            failed.append((Path(path), "nessuna scheda ADR (manca la riga «ID e titolo»)"))
    return sheets, failed


def create_adrs(project, planned):
    """The ADR chosen created in the model, with their IDs (or those given by ATLAS). Returns them."""
    created, by_ident = [], {}
    for p in planned:
        values = {k: v for k, v in p.values.items() if not k.startswith("_")}
        if p.ident:
            values["id"] = p.ident
        adr = project.new_element("adr", **values)
        created.append(adr)
        if p.ident:
            by_ident[p.ident] = adr
    for p, adr in zip(planned, created):
        later = p.values.get("_superseded_by")
        if later and later in by_ident:
            previous = adr.copy()
            adr.set("superseded_by", by_ident[later].uuid)
            project.update(adr, previous)
    return created

